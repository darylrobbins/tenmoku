//! The shapes the minimap draws characters with, as VS Code's does with
//! `editor.minimap.renderCharacters`: each printable ASCII char is an alpha
//! mask a column wide and a row tall, `scale` by `2 * scale` logical
//! pixels. gpui's glyph rasterizer is its own, so the masks come from VS
//! Code's prebaked sample data (src/vs/editor/browser/viewParts/minimap/
//! minimapPreBaked.ts, MIT), which it keeps for 1 and 2 device pixels a
//! column; other sizes are resampled from the 2-pixel data.

use std::sync::OnceLock;

/// The first char with a mask, a space, and the last, `~`.
const FIRST: u8 = b' ';
const LAST: u8 = b'~';

/// Chars in the sample data: the printable ASCII ones, then VS Code's
/// unknown char, which isn't drawn.
const SAMPLED: usize = (LAST - FIRST) as usize + 2;

/// The most device pixels a column a mask is kept at: scale 3 on a 2x
/// display. Wider columns stretch the widest.
pub(crate) const MAX_SCALE: u32 = 6;

/// How much of a sample's weight a char is drawn with, as VS Code softens
/// its normal-weight font by 12/15.
const WEIGHT: f32 = 12. / 15.;

/// What a minimap column is drawn as, with a run's colour.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Glyph {
    /// With characters off, a block (card 2's).
    Block,
    /// A printable ASCII char's mask.
    Char(u8),
    /// Another char, as a block at VS Code's half weight, over both columns
    /// of a wide one.
    Other,
}

impl Glyph {
    /// How `ch` is drawn with characters on.
    pub(crate) fn of(ch: char) -> Self {
        match ch {
            ' '..='~' => Self::Char(ch as u8),
            _ => Self::Other,
        }
    }
}

/// A char's alpha mask at some device pixels a column: `width` by
/// `height`, row by row.
#[derive(Clone, Copy, Debug)]
pub(crate) struct Mask {
    pub(crate) width: usize,
    pub(crate) height: usize,
    pub(crate) alpha: &'static [u8],
}

/// The device pixels a column is wide at minimap `scale` and the display's
/// `scale_factor`, as masks are kept: from 1 to [`MAX_SCALE`].
pub(crate) fn device_scale(scale: f32, scale_factor: f32) -> u32 {
    ((scale * scale_factor).round() as u32).clamp(1, MAX_SCALE)
}

/// The mask of `ch` at `scale` device pixels a column (see
/// [`device_scale`]): `scale` by `2 * scale`. `None` for a space, or a char
/// with no mask.
pub(crate) fn mask(ch: u8, scale: u32) -> Option<Mask> {
    if !(FIRST + 1..=LAST).contains(&ch) {
        return None;
    }
    let scale = scale.clamp(1, MAX_SCALE) as usize;
    static MASKS: [OnceLock<Vec<u8>>; MAX_SCALE as usize] =
        [const { OnceLock::new() }; MAX_SCALE as usize];
    let masks = MASKS[scale - 1].get_or_init(|| masks(scale));
    let size = scale * 2 * scale;
    let start = (ch - FIRST) as usize * size;
    Some(Mask {
        width: scale,
        height: 2 * scale,
        alpha: &masks[start..start + size],
    })
}

/// Every printable ASCII char's mask at `scale` device pixels a column, in
/// order, softened to [`WEIGHT`].
fn masks(scale: usize) -> Vec<u8> {
    let (width, height) = (scale, 2 * scale);
    let mut out = Vec::with_capacity(SAMPLED * width * height);
    for index in 0..SAMPLED - 1 {
        match scale {
            1 => out.extend(&SCALE_1[index * 2..index * 2 + 2]),
            _ => resample(&SCALE_2[index * 8..index * 8 + 8], 2, width, &mut out),
        }
    }
    for alpha in &mut out {
        *alpha = (*alpha as f32 * WEIGHT).round() as u8;
    }
    out
}

/// `sample`, `from` pixels by `2 * from`, as `to` by `2 * to`, each pixel
/// the average of the sample's under it, weighed by how much of each it
/// covers.
fn resample(sample: &[u8], from: usize, to: usize, out: &mut Vec<u8>) {
    let ratio = from as f32 / to as f32;
    // How much of sample pixel `n` the pixel `at` covers, in sample pixels.
    let cover = |at: usize, n: usize| {
        let (start, end) = (at as f32 * ratio, (at + 1) as f32 * ratio);
        (end.min(n as f32 + 1.) - start.max(n as f32)).max(0.)
    };
    for y in 0..2 * to {
        for x in 0..to {
            let mut sum = 0.;
            for sy in 0..2 * from {
                for sx in 0..from {
                    let weight = cover(x, sx) * cover(y, sy);
                    sum += weight * sample[sy * from + sx] as f32;
                }
            }
            out.push((sum / (ratio * ratio)).round().min(255.) as u8);
        }
    }
}

